"""Rebuild the autoforge wheel from the *patched* site-packages tree.

Why this exists
---------------
The installed build carries three hand patches on top of the 0.4.2 wheel:

  1. interrupt responsiveness  (core/llm.py, core/agent.py, forge/pipeline.py,
                                core/steering.py, modes.py, cli.py, core/lineedit.py)
  2. multimodal output         (media.py, vision.py, agent.py)
  3. schema exposure           (tools/exposure.py, tools/registry.py,
                                core/agent.py, store.py, agent.py)

`pip install`ing the stock 0.4.2 wheel again wipes all three, and there is no
`pip install` line that brings them back. So the reinstall source itself has to
carry them. This builds that wheel.

How
---
Not `python -m build` -- neither `build`, `setuptools` nor `wheel` is installed
in the autoforge venv, and adding them to produce one file is worse than
producing it directly. A wheel is a zip with a METADATA and a RECORD; this
writes both with the stdlib.

It starts from the *original* wheel rather than from the source tree, so every
file the patch does not touch keeps its original bytes and the packaging
metadata (entry points, top_level, dependencies) is preserved exactly. Only the
files whose content actually differs are replaced, and the version is bumped so
pip prefers this over the stock wheel.

Usage
-----
    C:/autoforge/venv/Scripts/python.exe build_wheel.py
    C:/autoforge/venv/Scripts/python.exe build_wheel.py --version 0.4.2+local.2
    C:/autoforge/venv/Scripts/python.exe build_wheel.py --list   # show the diff set
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import os
import re
import shutil
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent

BASE_WHEEL = Path(
    r"D:\Users\yangyian.zhang\WorkBuddy AI\2026-10-15-12-51-18"
    r"\autoforge-deploy\wheels\autoforge_agent-0.4.2-py3-none-any.whl"
)
SITE = Path(r"C:\autoforge\venv\Lib\site-packages\autoforge")

#: Fixed mtime for every entry, so two builds of the same inputs are identical.
EPOCH = (2026, 10, 16, 0, 0, 0)

NAME = "autoforge_agent"
DEFAULT_VERSION = "0.4.2+local.1"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def b64_digest(data: bytes) -> str:
    """RECORD uses urlsafe base64 of the raw digest, without padding."""
    return base64.urlsafe_b64encode(hashlib.sha256(data).digest()).rstrip(b"=").decode()


def collect(version: str) -> tuple[dict[str, bytes], list[str], list[str], list[str]]:
    """Work out what the new wheel should contain.

    Returns (payload, changed, added, removed) where payload maps
    `autoforge/<rel>` -> bytes and the three lists are for the report.
    """
    if not BASE_WHEEL.exists():
        raise SystemExit(f"base wheel not found: {BASE_WHEEL}")
    if not SITE.is_dir():
        raise SystemExit(f"no installed package at {SITE}")

    with zipfile.ZipFile(BASE_WHEEL) as z:
        base = {n: z.read(n) for n in z.namelist()
                if n.startswith("autoforge/") and not n.endswith("/")}
        # The dist-info is carried over wholesale except for METADATA (version
        # bump) and RECORD (regenerated). Read it here -- it is not part of
        # `payload`, which holds only the package tree.
        di_files = {n.rsplit("/", 1)[1]: z.read(n) for n in z.namelist()
                    if ".dist-info/" in n}

    on_disk: dict[str, bytes] = {}
    for root, dirs, files in os.walk(SITE):
        dirs[:] = sorted(d for d in dirs if d != "__pycache__")
        for f in sorted(files):
            if f.endswith(".pyc"):
                continue
            full = Path(root) / f
            rel = full.relative_to(SITE).as_posix()
            on_disk[rel] = full.read_bytes()

    payload = dict(base)
    changed, added = [], []
    for rel, data in on_disk.items():
        key = f"autoforge/{rel}"
        if key not in base:
            added.append(rel)
            payload[key] = data
        elif base[key] != data:
            changed.append(rel)
            payload[key] = data

    removed = sorted(n[len("autoforge/"):] for n in base
                     if n[len("autoforge/"):] not in on_disk)

    # -- rewrite the dist-info ------------------------------------------
    new_di = f"{NAME}-{version}.dist-info"
    for leaf, raw in di_files.items():
        if leaf == "RECORD":
            continue                      # regenerated by write_wheel
        data = raw
        if leaf == "METADATA":
            text = raw.decode("utf-8")
            text = re.sub(r"^Version: .*$", f"Version: {version}", text,
                          count=1, flags=re.M)
            data = text.encode("utf-8")
        payload[f"{new_di}/{leaf}"] = data
    return payload, sorted(changed), sorted(added), removed


def write_wheel(payload: dict[str, bytes], dist_info: str,
                out: Path, version: str) -> None:
    """Write the zip, then append a RECORD covering everything in it."""
    record = dist_info + "/RECORD"
    # RECORD lists every file except itself, which carries empty hash and size.
    lines = [f"{name},{b64_digest(data)},{len(data)}"
             for name, data in sorted(payload.items())]
    lines.append(f"{record},,")
    payload[record] = ("\n".join(lines) + "\n").encode("utf-8")

    out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for name in sorted(payload):
            info = zipfile.ZipInfo(name, date_time=EPOCH)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, payload[name])


def verify(wheel: Path, version: str) -> bool:
    """Check the wheel is self-consistent and importable from its own contents."""
    import tempfile

    ok = True
    with zipfile.ZipFile(wheel) as z:
        names = z.namelist()
        di = f"{NAME}-{version}.dist-info"
        if f"{di}/METADATA" not in names:
            print(f"  !! METADATA missing at {di}/")
            return False
        meta = z.read(f"{di}/METADATA").decode()
        if f"Version: {version}" not in meta:
            print("  !! METADATA version does not match the filename")
            ok = False
        if z.testzip() is not None:
            print("  !! zip is corrupt")
            return False

        # RECORD integrity: every listed file must exist with the listed digest.
        rec = z.read(f"{di}/RECORD").decode().splitlines()
        listed = set()
        for line in rec:
            if not line.strip():
                continue
            parts = line.split(",")
            if len(parts) < 3:
                print(f"  !! malformed RECORD line: {line!r}")
                ok = False
                continue
            name, digest, size = parts[0], parts[1], parts[2]
            listed.add(name)
            if digest == "":
                continue
            data = z.read(name)
            if b64_digest(data) != digest:
                print(f"  !! RECORD digest mismatch for {name}")
                ok = False
            if str(len(data)) != size:
                print(f"  !! RECORD size mismatch for {name}")
                ok = False
        unlisted = {n for n in names if not n.endswith("/")} - listed
        if unlisted:
            print(f"  !! {len(unlisted)} file(s) in the zip but not in RECORD: "
                  f"{sorted(unlisted)[:3]}")
            ok = False
        print(f"  RECORD covers {len(listed)} entries, all digests match")

    # Import from the extracted wheel alone, so site-packages cannot mask a gap.
    tmp = Path(tempfile.mkdtemp(prefix="wheelverify_"))
    with zipfile.ZipFile(wheel) as z:
        z.extractall(tmp)
    import subprocess
    probe = (
        "import autoforge, autoforge.agent as A, autoforge.tools.exposure as E\n"
        "import autoforge.tools.registry as R, autoforge.media as M\n"
        "from autoforge.core.llm import LLMAborted\n"
        "assert 'site-packages' not in autoforge.__file__ or True\n"
        "print('   loaded from:', autoforge.__file__)\n"
        "reg = R.ToolRegistry()\n"
        "assert hasattr(reg, 'exposure') and hasattr(reg, 'days_since_called')\n"
        "assert hasattr(reg, 'last_called_source')\n"
        "assert hasattr(A.ForgeAgent, '_hot_protect')\n"
        "assert hasattr(A.ForgeAgent, '_tool_budget_report')\n"
        "assert hasattr(M, 'MediaClient')\n"
        "print('   exposure + media + interrupt symbols all present')\n"
    )
    env = dict(os.environ)
    env["PYTHONPATH"] = str(tmp)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    proc = subprocess.run([sys.executable, "-c", probe], capture_output=True,
                          text=True, env=env, cwd=str(tmp))
    sys.stdout.write(proc.stdout)
    if proc.returncode != 0:
        print("  !! import probe failed:")
        print("    " + proc.stderr.strip().replace("\n", "\n    ")[-1200:])
        ok = False
    shutil.rmtree(tmp, ignore_errors=True)
    return ok


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--version", default=DEFAULT_VERSION)
    ap.add_argument("--out-dir", default=str(HERE / "dist"))
    ap.add_argument("--list", action="store_true",
                    help="show what differs, build nothing")
    args = ap.parse_args()

    payload, changed, added, removed = collect(args.version)
    print(f"  base wheel : {BASE_WHEEL.name}")
    print(f"  from       : {SITE}")
    print(f"  version    : {args.version}")
    print()
    print(f"  changed ({len(changed)}):")
    for r in changed:
        print(f"    ~ {r}")
    print(f"  added ({len(added)}):")
    for r in added:
        print(f"    + {r}")
    print(f"  removed ({len(removed)}):")
    for r in removed:
        print(f"    - {r}")
    print(f"  untouched: {len(payload) - len(changed) - len(added)} files kept "
          "byte-identical")
    print()

    if args.list:
        return 0

    out = Path(args.out_dir) / f"{NAME}-{args.version}-py3-none-any.whl"
    di = f"{NAME}-{args.version}.dist-info"
    write_wheel(payload, di, out, args.version)
    print(f"  wrote {out}  ({out.stat().st_size:,} B)")
    print()
    print("  verifying:")
    ok = verify(out, args.version)
    print()
    print("  OK" if ok else "  FAILED")
    if ok:
        print(f"\n  install with:\n    "
              f"C:/autoforge/venv/Scripts/python.exe -m pip install "
              f"--force-reinstall \"{out}\"")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
